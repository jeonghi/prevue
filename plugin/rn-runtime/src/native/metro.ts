import type { EventEmitter } from 'node:events';
import { mkdir, readFile, realpath, rm, stat } from 'node:fs/promises';
import { createServer, type IncomingMessage, type ServerResponse } from 'node:http';
import { createRequire } from 'node:module';
import path from 'node:path';
import { atomicWrite } from '../instance.ts';
import { PreviewFailure } from '../errors.ts';
import { discover } from '../registry.ts';

const marker = '// Generated by Prevue for this debug session.';
export async function writeEntry(root: string, platform: 'ios' | 'android', revision: string, endpoint: string, token: string) {
  const directory = path.join(root, '.prevue');
  await mkdir(directory, { recursive: true, mode: 0o700 });
  if (await realpath(directory) !== directory) throw new PreviewFailure('UNSAFE_NATIVE_ENTRY', 'The .prevue directory must be inside this project.');
  const file = path.join(directory, 'entry.' + platform + '.js');
  const prior = await readFile(file, 'utf8').catch(error => {
    if (error.code !== 'ENOENT') throw error;
    return undefined;
  });
  if (prior !== undefined && !prior.startsWith(marker + '\n')) throw new PreviewFailure('UNSAFE_NATIVE_ENTRY', 'Refusing to replace existing source ' + file);
  const previews = (await discover(root)).filter(preview => preview.platforms.includes(platform));
  const provider = await stat(path.join(root, 'prevue.providers.tsx')).then(s => s.isFile(), () => false);
  const imports = previews.map(({ id, source }) => `    ${JSON.stringify(id)}: () => require(${JSON.stringify('../' + source.file)})[${JSON.stringify(source.exportName)}],`);
  const lines = [marker, "import {createPreviewHost} from '@prevue/native-host';", 'export default createPreviewHost({',
    `  revision: ${JSON.stringify(revision)}, endpoint: ${JSON.stringify(endpoint)}, token: ${JSON.stringify(token)},`,
    ...(provider ? ["  provider: require('../prevue.providers.tsx').default,"] : []), '  registry: {', ...imports, '  },', '});', ''];
  await atomicWrite(file, lines.join('\n'));
  return async () => {
    const current = await readFile(file, 'utf8').catch(() => '');
    if (current.startsWith(marker) && current.includes(JSON.stringify(token))) await rm(file);
  };
}

type MetroChange = {
  rootDir: string;
  changes?: { addedFiles: Iterable<[string, unknown]>; modifiedFiles: Iterable<[string, unknown]>; removedFiles: Iterable<[string, unknown]> };
  eventsQueue?: { filePath: string }[];
};
interface MetroMiddleware {
  middleware(req: IncomingMessage, res: ServerResponse, next: (error?: Error) => void): void;
  attachHmrServer(server: ReturnType<typeof createServer>): void;
  metroServer: { getBundler(): { getBundler(): { getDependencyGraph(): Promise<{ getWatcher(): EventEmitter }> } } };
  end(): Promise<void>;
}
interface MetroAPI {
  loadConfig(options: { cwd: string; port: number; maxWorkers: number }): Promise<Record<string, unknown>>;
  createConnectMiddleware(config: Record<string, unknown>, options: { waitForBundler: boolean }): Promise<MetroMiddleware>;
}

export async function startMetro(root: string, cache: string, changed: (file: string) => void) {
  const require = createRequire(path.join(root, 'package.json'));
  let metro: MetroAPI;
  try { metro = require('metro') as MetroAPI; } catch {
    throw new PreviewFailure('METRO_UNAVAILABLE', 'Install Metro and configure metro.config.js in the selected debug host.');
  }
  let connection: MetroMiddleware | undefined;
  const server = createServer((req, res) => {
    const address = server.address();
    if (!address || typeof address === 'string' || !['127.0.0.1:' + address.port, 'localhost:' + address.port].includes(req.headers.host ?? '') ||
        (req.headers.origin && req.headers.origin !== 'http://' + req.headers.host)) { res.writeHead(403).end(); return; }
    if (req.url === '/status') { res.end('packager-status:running'); return; }
    if (!connection) { res.writeHead(503).end(); return; }
    connection.middleware(req, res, error => res.writeHead(error ? 500 : 404).end(error?.message));
  });
  await new Promise<void>((resolve, reject) => server.once('error', reject).listen(0, '127.0.0.1', resolve));
  const address = server.address();
  if (!address || typeof address === 'string') throw new Error('Missing Metro address');
  try {
    const config = await metro.loadConfig({ cwd: root, port: address.port, maxWorkers: 2 });
    await mkdir(cache, { recursive: true, mode: 0o700 });
    const metroRequire = createRequire(require.resolve('metro/package.json'));
    const { FileStore } = metroRequire('metro-cache') as { FileStore: new (options: { root: string }) => unknown };
    config.cacheStores = [new FileStore({ root: path.join(cache, 'transform') })];
    config.fileMapCacheDirectory = cache;
    connection = await metro.createConnectMiddleware(config, { waitForBundler: true });
    connection.attachHmrServer(server);
    const graph = await connection.metroServer.getBundler().getBundler().getDependencyGraph();
    const watcher = graph.getWatcher();
    const onChange = (event: MetroChange) => {
      const paths = event.changes ?
        [...event.changes.addedFiles, ...event.changes.modifiedFiles, ...event.changes.removedFiles].map(([relative]) => path.resolve(event.rootDir, relative)) :
        (event.eventsQueue ?? []).map(item => item.filePath);
      for (const file of new Set(paths)) {
        if (!file.split(path.sep).some(part => ['.git', '.prevue', 'node_modules', 'Pods', 'build', '.gradle', '.cache'].includes(part))) changed(file);
      }
    };
    watcher.on('change', onChange);
    return { port: address.port, async close() {
      watcher.off('change', onChange);
      server.closeAllConnections(); server.close();
      await connection?.end();
    } };
  } catch (error) {
    server.closeAllConnections(); server.close();
    await connection?.end();
    throw error;
  }
}
