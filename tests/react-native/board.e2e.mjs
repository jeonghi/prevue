import assert from 'node:assert/strict';
import { readFile, writeFile, unlink } from 'node:fs/promises';
import path from 'node:path';
import { test } from 'node:test';
import { center, chromium, digest, keep, projects, treeNodes } from './projects.mjs';

test('RN viewer, saved source, error recovery, interaction and independent worktrees', {timeout:240000},async t=>{
  const suite=await projects(3); t.after(()=>suite.close());
  const [a,b,c]=suite.roots;
  const cli=(...args)=>suite.cli(a,args);
  const show=root=>suite.cli(root,['show','OrderCard.preview.tsx','--lang','ko']);
  const [first,other,third]=await Promise.all(suite.roots.map(show));
  assert.equal(first.platform,'web');
  assert.deepEqual(first.cards.map(p=>p.name),['Default','Loading','Error']);
  assert.equal(new Set([first,other,third].map(v=>new URL(v.viewer).port)).size,3);
  const original=await digest(first.cards[0].imagePath);
  await keep(first.cards[0].imagePath,'before.png');
  const browser=await chromium.launch();t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1440,height:880},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',err=>errors.push(err.message));
  const origin=new URL(first.viewer).origin;
  assert.equal((await fetch(origin+'/viewer/state')).status,401);
  await page.goto(first.viewer);
  await page.waitForFunction(()=>[...document.querySelectorAll('.card .cstage img')].filter(img=>img.complete && img.naturalWidth>0).length===3);
  const files=await page.evaluate(async()=>await (await fetch('/preview-files.json')).json());
  assert.ok(files.files.some(f=>f.path.endsWith('OrderCard.preview.tsx')));
  const session=await page.evaluate(async()=>await (await fetch('/viewer/state')).json());
  assert.equal(session.screen,'board');
  const gallery=await page.evaluate(async file=>await(await fetch('/gallery/card?file='+encodeURIComponent(file))).json(),files.files[0].path);
  assert.ok(gallery);
  if(process.env.PREVUE_DEMO_DIR) await page.screenshot({path:path.join(process.env.PREVUE_DEMO_DIR,'board.png')});
  const file=path.join(a,'OrderCard.tsx'), source=await readFile(file,'utf8');
  async function edit(file,content,base,code=0) {
    await writeFile(file,content);
    const board=await suite.cli(a,['wait',path.relative(a,file),'--after',String(base),'--timeout','30'],code);
    assert.ok(board.generation>base,JSON.stringify(board));
    return board;
  }
  const padded=source.replace('padding: 22','padding: 36');assert.notEqual(source,padded);
  const saved=await edit(file,padded,first.generation);
  assert.equal(saved.cards[0].imageGeneration,saved.generation);
  assert.notEqual(await digest(saved.cards[0].imagePath),original);
  await keep(saved.cards[0].imagePath,'padding-36.png');
  await page.waitForFunction(async gen=>(await(await fetch('/viewer/state')).json()).board.gen>=gen,saved.generation);
  const same=await suite.cli(b,['board']);assert.equal(same.generation,other.generation);
  assert.equal(await digest(same.cards[0].imagePath),await digest(other.cards[0].imagePath));
  const broken=await edit(file,padded+'\nexport const impossible = ( ;',saved.generation,1);
  assert.equal(broken.cards[0].status,'stale');assert.equal(broken.cards[0].imageGeneration,saved.generation);
  assert.equal(await digest(broken.cards[0].imagePath),await digest(saved.cards[0].imagePath));
  const fixed=await edit(file,source,broken.generation);
  assert.equal(await digest(fixed.cards[0].imagePath),original);
  const palette=path.join(a,'theme.tsx'), colors=await readFile(palette,'utf8');
  const changedColors=colors.replace('#FFFFFF','#FFCC77');assert.notEqual(changedColors,colors);
  const shared=await edit(palette,changedColors,fixed.generation);
  assert.notEqual(await digest(shared.cards[0].imagePath),original);
  const textChanged=source.replace("origin: '부산'","origin: '울산'");
  const renamed=await edit(file,textChanged,shared.generation);
  assert.ok((await treeNodes(renamed.cards[0])).some(node=>node.text?.includes('울산')));
  const nested=textChanged.replace('{order.origin} → {order.destination}','<Text testID="route-inner">{order.origin} → {order.destination}</Text>');
  const rearranged=await edit(file,nested,renamed.generation);
  assert.ok((await treeNodes(rearranged.cards[0])).some(node=>node.testId==='route-inner'));
  const extra=path.join(a,'Extra.preview.tsx');
  const added=await edit(extra,"import {definePreview} from '@prevue/react-native'; import {Text} from 'react-native'; export const Extra=definePreview({render:()=> <Text>Extra</Text>});",rearranged.generation);
  assert.ok((await cli('previews')).previews.some(p=>p.source.file==='Extra.preview.tsx'));
  await unlink(extra);
  await cli('wait','--after',String(added.generation));
  assert.ok(!(await cli('status')).previews.some(p=>p.source.file==='Extra.preview.tsx'));
  const focus=await cli('focus','0','--on');
  const button=(await treeNodes(focus)).find(n=>n.testId==='order-detail');assert.ok(button);
  const tapped=await cli('touch',...center(button));
  assert.ok((await treeNodes(tapped)).some(n=>n.testId==='order-route-detail'));
  const reset=await cli('reset');assert.ok(!(await treeNodes(reset)).some(n=>n.testId==='order-route-detail'));
  await cli('focus','0','--off');
  await page.keyboard.press('/');
  const search=page.locator('#qoSheet input');
  await search.fill('Controls');
  await page.locator('#qoIn [role="option"]').first().waitFor();
  await search.press('Enter');
  await page.waitForFunction(()=>document.querySelectorAll('.card .cstage img').length===8);
  const controls=await cli('board');
  assert.equal(controls.file,'examples/Controls.preview.tsx');
  const inputView=await cli('focus',String(controls.cards.findIndex(card=>card.name==='TextInput')),'--on');
  const input=(await treeNodes(inputView)).find(n=>n.testId==='shipment-note');assert.ok(input);
  await cli('touch',...center(input));
  const typed=await cli('type','후문');
  assert.ok((await treeNodes(typed)).some(n=>n.testId==='shipment-note' && n.text==='후문'));
  const scrollView=await cli('focus',String(controls.cards.findIndex(card=>card.name==='ScrollView')),'--on');
  const scrolled=await cli('scroll','--direction','down');
  assert.notEqual(await digest(scrollView.imagePath),await digest(scrolled.imagePath));
  await cli('stop');
  assert.equal((await suite.cli(b,['status'])).generation,other.generation);
  assert.equal((await suite.cli(c,['board'])).generation,third.generation);
  assert.deepEqual(errors,[]);
});
